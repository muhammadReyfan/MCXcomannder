CREATE TABLE IF NOT EXISTS users (
  id BIGSERIAL PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS tasks (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(200) NOT NULL, category VARCHAR(60) NOT NULL DEFAULT 'Pribadi', priority VARCHAR(20) NOT NULL DEFAULT 'Sedang' CHECK(priority IN ('Rendah','Sedang','Tinggi')),
  deadline DATE, project VARCHAR(120) NOT NULL DEFAULT '', notes TEXT NOT NULL DEFAULT '', completed BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS projects (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name VARCHAR(160) NOT NULL, description TEXT NOT NULL DEFAULT '', status VARCHAR(30) NOT NULL DEFAULT 'Belum mulai', deadline DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS goals (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(200) NOT NULL, description TEXT NOT NULL DEFAULT '', timeframe VARCHAR(30) NOT NULL DEFAULT 'Bulanan', target_date DATE,
  status VARCHAR(30) NOT NULL DEFAULT 'Aktif', created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS milestones (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  goal_id BIGINT REFERENCES goals(id) ON DELETE CASCADE, title VARCHAR(200) NOT NULL, target_date DATE,
  completed BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS habits (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(160) NOT NULL, frequency VARCHAR(30) NOT NULL DEFAULT 'Harian', created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS habit_logs (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  habit_id BIGINT NOT NULL REFERENCES habits(id) ON DELETE CASCADE, log_date DATE NOT NULL, completed BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE(habit_id, log_date)
);
CREATE TABLE IF NOT EXISTS fitness_logs (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  activity VARCHAR(120) NOT NULL, duration_minutes INTEGER NOT NULL DEFAULT 0 CHECK(duration_minutes >= 0), notes TEXT NOT NULL DEFAULT '', log_date DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS study_sessions (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  subject VARCHAR(120) NOT NULL, duration_minutes INTEGER NOT NULL DEFAULT 0 CHECK(duration_minutes >= 0), notes TEXT NOT NULL DEFAULT '', study_date DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS finance_transactions (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type VARCHAR(20) NOT NULL CHECK(type IN ('Pemasukan','Pengeluaran')), amount NUMERIC(14,2) NOT NULL CHECK(amount > 0), category VARCHAR(80) NOT NULL, description TEXT NOT NULL DEFAULT '', transaction_date DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS savings_goals (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(160) NOT NULL, target_amount NUMERIC(14,2) NOT NULL CHECK(target_amount > 0), saved_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(saved_amount >= 0), target_date DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS weekly_reviews (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  week_start DATE NOT NULL, wins TEXT NOT NULL DEFAULT '', challenges TEXT NOT NULL DEFAULT '', next_week TEXT NOT NULL DEFAULT '', mood VARCHAR(40) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), UNIQUE(user_id, week_start)
);
CREATE INDEX IF NOT EXISTS tasks_user_id_idx ON tasks(user_id);
CREATE INDEX IF NOT EXISTS projects_user_id_idx ON projects(user_id);
CREATE INDEX IF NOT EXISTS goals_user_id_idx ON goals(user_id);
CREATE INDEX IF NOT EXISTS finance_user_date_idx ON finance_transactions(user_id, transaction_date);
